import { contextBridge, ipcRenderer } from 'electron'

const on = (channel) => (cb) => {
  const fn = (_e, v) => cb(v)
  ipcRenderer.on(channel, fn)
  return () => ipcRenderer.removeListener(channel, fn)
}

contextBridge.exposeInMainWorld('glowtide', {
  init: () => ipcRenderer.invoke('init'),
  onState: on('state'),
  onLyrics: on('lyrics'),
  onSettings: on('settings'),
  onDebugPanel: on('debug:panel'),
  onOpenPanel: on('panel:open'),
  onYtCommand: on('yt:command'),
  ytState: (m) => ipcRenderer.send('yt:state', m),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  control: (action, arg) => ipcRenderer.invoke('control', action, arg),
  query: (kind, arg) => ipcRenderer.invoke('query', kind, arg),
  setSource: (src) => ipcRenderer.invoke('source', src),
  selectSystemApp: (appId) => ipcRenderer.invoke('system:select', appId),
  nudgeLyrics: (delta) => ipcRenderer.invoke('lyrics:nudge', delta),
  saveTimedLyrics: (lines, trackId) => ipcRenderer.invoke('lyrics:saveTimed', lines, trackId),
  removeTimedLyrics: () => ipcRenderer.invoke('lyrics:removeTimed'),
  stats: (range) => ipcRenderer.invoke('stats:get', range),
  clearHistory: () => ipcRenderer.invoke('history:clear'),
  favsForSong: () => ipcRenderer.invoke('favs:forSong'),
  toggleFav: (text, trackId) => ipcRenderer.invoke('favs:toggle', text, trackId),
  allFavs: () => ipcRenderer.invoke('favs:all'),
  yearInMusic: (year) => ipcRenderer.invoke('stats:year', year),
  removeFav: (key, text) => ipcRenderer.invoke('favs:remove', key, text),
  timingHint: (trackId, offsetMs) => ipcRenderer.invoke('timing:hint', trackId, offsetMs),
  dismissTiming: () => ipcRenderer.invoke('timing:dismiss'),
  saveClip: (bytes, name, ext) => ipcRenderer.invoke('clip:save', bytes, name, ext),
  exportBackup: () => ipcRenderer.invoke('backup:export'),
  importBackup: () => ipcRenderer.invoke('backup:import'),
  remoteStatus: () => ipcRenderer.invoke('remote:status'),
  remotePair: () => ipcRenderer.invoke('remote:pair'),
  remoteForget: () => ipcRenderer.invoke('remote:forget'),
  exportTimedLyrics: () => ipcRenderer.invoke('lyrics:exportTimed'),
  lyricsCandidates: (q) => ipcRenderer.invoke('lyrics:candidates', q),
  chooseLyrics: (id) => ipcRenderer.invoke('lyrics:choose', id),
  pickBackground: () => ipcRenderer.invoke('background:pick'),
  sharePreview: () => ipcRenderer.invoke('lyrics:sharePreview'),
  shareLrclib: (trackId) => ipcRenderer.invoke('lyrics:shareLrclib', trackId),
  cardCover: (url) => ipcRenderer.invoke('card:cover', url),
  copyCard: (png) => ipcRenderer.invoke('card:copy', png),
  saveCard: (png, name) => ipcRenderer.invoke('card:save', png, name),
  connect: () => ipcRenderer.invoke('auth:connect'),
  disconnect: () => ipcRenderer.invoke('auth:disconnect'),
  googleConnect: () => ipcRenderer.invoke('google:connect'),
  googleDisconnect: () => ipcRenderer.invoke('google:disconnect'),
  windowAction: (a) => ipcRenderer.invoke('window', a),
  displays: () => ipcRenderer.invoke('displays'),
  stage: (action) => ipcRenderer.invoke('stage', action),
  open: (url) => ipcRenderer.invoke('open', url),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  quit: () => ipcRenderer.invoke('app:quit'),
  showPlayer: () => ipcRenderer.invoke('player:show'),
  closeQuick: () => ipcRenderer.invoke('quick:close'),
  closeCommand: () => ipcRenderer.invoke('command:close'),
  onCommandOpen: on('command:open'),
  onCommandListen: on('command:listen'),
  voiceStatus: () => ipcRenderer.invoke('voice:status'),
  voiceDownload: () => ipcRenderer.invoke('voice:download'),
  voiceRemove: () => ipcRenderer.invoke('voice:remove'),
  voiceHold: (on) => ipcRenderer.invoke('voice:hold', !!on),
  // the wake word's microphone feed (the command bar window)
  onVoiceFeed: on('voice:feed'),
  voiceFeedWanted: () => ipcRenderer.invoke('voice:feedWanted'),
  voicePcm: (buf) => ipcRenderer.send('voice:pcm', buf),
  voiceFeedError: (msg) => ipcRenderer.invoke('voice:feedError', msg),
  onWindowVisible: on('window:visible'),
  share: () => ipcRenderer.invoke('share'),
  recordingShortcut: (on) => ipcRenderer.invoke('shortcuts:recording', !!on)
})
